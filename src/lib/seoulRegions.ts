export function composeJibunDetail(main: string, sub: string): string {
  const a = main.trim();
  const b = sub.trim();
  if (a && b) return `${a}-${b}`;
  return a || b;
}

export function parseJibunDetail(detail: string): { main: string; sub: string } {
  const text = detail.trim();
  if (!text) return { main: "", sub: "" };
  const dash = text.indexOf("-");
  if (dash >= 0) {
    return {
      main: text.slice(0, dash).trim(),
      sub: text.slice(dash + 1).trim(),
    };
  }
  return { main: text, sub: "" };
}

export function composeSeoulAddress(
  gu: string,
  dong: string,
  detail: string
): string {
  const parts = ["서울", gu, dong, detail.trim()].filter(Boolean);
  return parts.join(" ");
}

/** 저장된 주소에서 구·동·상세 분리 시도 */
export function parseSeoulAddress(address: string): {
  gu: string;
  dong: string;
  detail: string;
} {
  const text = address.trim();
  if (!text) return { gu: "", dong: "", detail: "" };

  const normalized = text.replace(/^서울(특별시)?\s*/, "서울 ");
  const withDong = normalized.match(
    /^서울\s+([가-힣]+구)\s+([가-힣0-9]+동|[가-힣0-9]+가|[가-힣]+로[0-9가]*)\s*(.*)$/
  );
  if (withDong) {
    return {
      gu: withDong[1] ?? "",
      dong: withDong[2] ?? "",
      detail: (withDong[3] ?? "").trim(),
    };
  }

  // 동 없이 구만 있는 경우 (예: 서울 강동구 / 서울 강동구 123-45)
  const guOnly = normalized.match(/^서울\s+([가-힣]+구)(?:\s+(.*))?$/);
  if (guOnly) {
    return {
      gu: guOnly[1] ?? "",
      dong: "",
      detail: (guOnly[2] ?? "").trim(),
    };
  }

  return { gu: "", dong: "", detail: text };
}
